"""What an export says about how it was made: the box kind, the models, the voice's source and
its consent, the EU AI Act's Article 50 label, the licences. mnm records and words; it never
refuses an export: a release-marked export whose voice has no consent recorded gets a note, in
`disclosure.txt`, the run record and on the page.

The label is one sentence, `ARTICLE_50_LABEL`, which GUIDE §28.6 quotes: Article 50(4) asks
whoever deploys AI-generated or manipulated audio to disclose it (in force 2026-08-02).
"""

from __future__ import annotations

from pathlib import Path

from makenomistakes.hardware.fingerprint import cards_words
from makenomistakes.machine_facts import MachineFactsError, load_file
from makenomistakes.run_parts import InputRecord, ModelCredit
from makenomistakes.studio.voice_library import (
    DISCLOSED_WORDS,
    ENGINE_WORDS,
    NEEDS_CONSENT,
    VoiceRow,
    VoiceTake,
)

ARTICLE_50_LABEL = (
    "This audio was generated or manipulated with artificial intelligence "
    "(disclosed under Article 50 of the EU AI Act)."
)
# What the recording's voice is to the export: a recording the song model sings around or
# continues carries the voice of whoever sang it; a reference only steers the style.
VOICED_USES = frozenset({"complete", "vocal2bgm"})


def box_words(state_dir: Path) -> str:
    """`RTX 4070 12 GB (x16 Gen4), WSL`: the cards and the platform as last read (card
    model names are not secret; no identifier is ever written)."""
    try:
        found = load_file(state_dir)
    except (MachineFactsError, OSError, ValueError):
        found = None
    if found is None or found.current is None:
        return "a box mnm has not read yet"
    box = found.current.fingerprint
    cards = cards_words(box.cards) if box.cards else "a box with no card"
    return f"{cards}, {box.platform.words()}"


def credit_words(credit: ModelCredit) -> str:
    """`song (audio-cpp/audio.cpp-gguf ACE-Step1.5-GGUF/turbo/… Q8_0)`; a style
    `the style lofi (a LoRA trained on 12 of the maker's own songs, adapter sha256 0a1b2c…)`."""
    if credit.style is not None:
        parts = [p for p in (credit.trained_on, f"adapter sha256 {(credit.sha256 or '')[:12]}…"
                             if credit.sha256 else None) if p]  # fmt: skip
        return f"the style {credit.style}" + (f" ({', '.join(parts)})" if parts else "")
    made = " ".join(p for p in (credit.repo, credit.file, credit.quant) if p)
    who = credit.instance or credit.workflow or credit.tool or "a model"
    return f"{who} ({made})" if made else who


def voice_words(recording: InputRecord | None, use: str | None) -> tuple[str, bool]:
    """The voice line and whether a consent document would be wanted for a release."""
    if recording is None or use not in VOICED_USES:
        return "generated by the song model from its tags (no voice row, no recording)", False
    short = recording.sha256[:12]
    return (
        f"from the maker's recording {recording.name} (sha256 {short}…, used as {use}); "
        "consent: none recorded",
        True,
    )


def take_words(take: VoiceTake, row: VoiceRow | None) -> tuple[str, str | None]:
    """The voice line for a library voice as it sang: its files by hash and whose it
    is, its consent from the library while the row is still that voice; and the note a
    release would carry when no consent is on record for a voice that wants one."""
    made = ", ".join(f"{f.role} sha256 {f.sha256[:12]}…" for f in take.files)
    whose = DISCLOSED_WORDS[take.source]
    same = take.same_voice(row)
    since = "" if same else (f"; the library's {take.voice} has been removed or replaced since")
    recorded = row.consent if same and row is not None else None
    consent = ""
    if take.source in NEEDS_CONSENT:
        consent = (
            f"; consent recorded {recorded.date} (sha256 {recorded.sha256[:12]}…)"
            if recorded is not None
            else "; consent: none recorded"
            if same
            else "; consent: not known here"
        )
    line = (
        f"sung in the library voice {take.voice} ({ENGINE_WORDS[take.engine]}, {made}; "
        f"{whose}{consent}{since})"
    )
    wants = take.source in NEEDS_CONSENT and recorded is None
    return line, voice_release_note(take) if wants else None


def voice_release_note(take: VoiceTake) -> str:
    return (
        f"Marked for release, and no consent document is on record for the library voice "
        f"{take.voice} ({DISCLOSED_WORDS[take.source]}): `mnm voices consent {take.voice} "
        "<document>` records one by its hash. mnm exported it anyway: what you release is "
        "yours to clear."
    )


def release_note(recording: InputRecord | None) -> str:
    name = recording.name if recording is not None else "the recording"
    return (
        f"Marked for release, and the voice in {name} has no consent document recorded "
        "(a voice in the library keeps one by its hash: `mnm voices add`, then `mnm voices "
        "consent`). mnm exported it anyway: what you release is yours to clear."
    )


def text(
    box: str,
    models: list[ModelCredit],
    voice: str,
    licences: list[str],
    notes: list[str],
    when: str,
) -> str:
    lines = [
        f"Made with mnm on {box}, {when}.",
        "Models: " + ("; ".join(credit_words(m) for m in models) or "none recorded") + ".",
        f"Voice: {voice}.",
        ARTICLE_50_LABEL,
        "Licences: " + ("; ".join(licences) or "none recorded") + ".",
        *notes,
    ]
    return "\n".join(lines) + "\n"
